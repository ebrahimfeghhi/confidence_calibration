#!/usr/bin/env python
"""Per-cluster composition of the audited SAbDab2 pool: structures, and what fraction are post-cutoff.

    ./cluster_composition.py > ../docs/cluster_composition.md

A cluster is an `ab_ag_cluster` in `data/zenodo_splits/splits_final/abag_split.csv`. A "complex" here
is a distinct PDB entry (`PDB_ID`); one entry can hold several antibody-antigen instances, and the
instance count is given separately.

Post-cutoff means `PDBdepo > 2021-09-30`, Protenix v2's wwPDB training cutoff. The fraction matters
because holding a cluster out of training costs the post-cutoff structures in it (the ones that teach
the confidence head about systems Protenix has not fitted), while a cluster with pre-cutoff
structures gives a weaker test: a "new" structure there is a fresh crystal of a system Protenix
trained on.
"""
import csv
import os
import collections
import sys

REPO = "/home/ebrahim/tts_abag/extra_training"
SPLIT = f"{REPO}/data/zenodo_splits/splits_final/abag_split.csv"
CUT = "2021-09-30"


def main():
    train = {r["cluster"] for r in csv.DictReader(open(f"{REPO}/results/train_clusters.csv"))}
    # LIVE split, not val_clusters.csv: that file is the legacy 50-cluster draw and 22 of the live
    # 40 clusters are absent from it, so composition computed against it describes a split we no
    # longer use. See phase_b_define_val_clusters.LIVE_VAL.
    val = {str(r["cluster"]) for r in
           csv.DictReader(open(f"{REPO}/results/val_split_proposal_clusters.csv"))}
    pool = train | val
    # THE LIVE FOLD, val2_*, not val_*. val_jobs/manifest.csv is the 77-job manifest of the
    # SUPERSEDED 50-cluster run; reading it labelled only the 22 clusters common to both as being
    # folded, while 18 live validation clusters showed as "val" and the rest of the live set was
    # invisible. val2_fold has no skipped.csv (nothing was skipped), so its absence is not an error.
    vman = list(csv.DictReader(open(f"{REPO}/val2_jobs/manifest.csv")))
    sk = f"{REPO}/val2_fold/skipped.csv"
    skips = ({r["pdb"] for r in csv.DictReader(open(sk))} if os.path.exists(sk) else set())
    folding = {m["cluster"] for m in vman if m["pdb"] not in skips}

    pre, post, inst = (collections.defaultdict(set), collections.defaultdict(set),
                       collections.Counter())
    for r in csv.DictReader(open(SPLIT)):
        c = str(r["ab_ag_cluster"])
        if c not in pool:
            continue
        inst[c] += 1
        (post if (r["PDBdepo"] or "")[:10] > CUT else pre)[c].add(r["PDB_ID"])

    rows = []
    for c in pool:
        npre, npost = len(pre[c]), len(post[c])
        n = npre + npost
        rows.append((c, n, npre, npost, (npost / n if n else 0.0), inst[c],
                     "val-folding" if c in folding else ("val" if c in val else "train")))
    rows.sort(key=lambda t: (-t[3], -t[1]))

    allnew = [r for r in rows if r[3] and not r[2]]
    mixed = [r for r in rows if r[3] and r[2]]
    oldonly = [r for r in rows if not r[3]]
    S = lambda rs, i: sum(r[i] for r in rs)

    print("# Per-cluster composition of the audited pool\n")
    print("Generated by `scripts/cluster_composition.py`. A cluster is an `ab_ag_cluster`; a complex "
          "is a distinct PDB entry; post-cutoff is `PDBdepo > 2021-09-30`.\n")
    print("## Summary\n")
    print("| group | clusters | complexes | post-cutoff complexes | instances |")
    print("|---|---|---|---|---|")
    for lbl, rs in (("all new (no pre-cutoff structure)", allnew),
                    ("mixed (both eras)", mixed),
                    ("all old (no post-cutoff structure)", oldonly)):
        print(f"| {lbl} | {len(rs)} | {S(rs,1)} | {S(rs,3)} | {S(rs,5)} |")
    print(f"| **total** | {len(rows)} | {S(rows,1)} | {S(rows,3)} | {S(rows,5)} |")
    print()
    print("`all new` clusters are the only clean generalisation test: no older structure of that "
          "system exists, so Protenix cannot have fitted a relative of it. In a `mixed` cluster a "
          "post-cutoff structure is a fresh crystal of a system Protenix trained on.\n")
    print("Holding a cluster out of training costs the post-cutoff complexes in it. An `all new` "
          "cluster with one complex costs one; a mixed cluster costs its post-cutoff share while its "
          "pre-cutoff structures are withheld too, and those are the ones Protenix already fits.\n")
    # THE CURRENT VALIDATION SET, called out rather than left as a column value in 533 rows. The
    # set is under review, and the question is which clusters give a clean test for what they cost.
    vrows = [r for r in rows if r[6] == "val-folding"]
    folded = collections.Counter()
    for m in vman:
        if m["pdb"] not in skips:
            folded[m["cluster"]] += 1
    print("## The 21 clusters currently in the validation fold\n")
    print("| cluster | kind | complexes | pre-cutoff | post-cutoff | % post | folded | instances |")
    print("|---|---|---|---|---|---|---|---|")
    for c, n, npre, npost, frac, ni, _ in sorted(vrows, key=lambda t: (bool(t[2]), -t[3])):
        kind = "mixed" if npre else "all new"
        print(f"| {c} | {kind} | {n} | {npre} | {npost} | {100*frac:.0f}% | {folded[c]} | {ni} |")
    vp = sum(r[3] for r in vrows)
    print(f"\n{len(vrows)} clusters: {sum(1 for r in vrows if not r[2])} all new, "
          f"{sum(1 for r in vrows if r[2])} mixed. They hold {vp} post-cutoff complexes "
          f"({100*vp/S(rows,3):.1f}% of the pool's {S(rows,3)}), of which "
          f"{sum(folded.values())} are folded.\n")
    print("`folded` is how many of that cluster's structures are in the running 100-seed fold -- "
          "phase G took up to two per cluster, so a cluster with many post-cutoff complexes "
          "contributes at most two.\n")
    # THE ACTUAL STRUCTURES, by name. "folded: 2" does not tell you which two, and the redesign
    # discussion needs the identities.
    pool_if = collections.Counter()
    for r in csv.DictReader(open(f"{REPO}/val_fold/pool.csv")):
        pool_if[r["pdb"]] += 1
    print("## The 28 structures in the validation fold\n")
    print("| cluster | kind | pdb | deposited | tokens | interfaces | instance |")
    print("|---|---|---|---|---|---|---|")
    act = [m for m in vman if m["pdb"] not in skips]
    kind_of = {r[0]: ("mixed" if r[2] else "all new") for r in rows}
    for m in sorted(act, key=lambda m: (kind_of.get(m["cluster"], "?"), int(m["cluster"]),
                                        m["deposited"])):
        print(f"| {m['cluster']} | {kind_of.get(m['cluster'],'?')} | {m['pdb']} | "
              f"{m['deposited']} | {m['n_tokens']} | {pool_if[m['pdb']]} | {m['instance']} |")
    print(f"\n{len(act)} structures over {len({m['cluster'] for m in act})} clusters, "
          f"{sum(pool_if[m['pdb']] for m in act)} interfaces. `instance` is the SAbDab2 instance "
          f"phase G built the job from. All are deposited after 2021-09-30; the 49 pre-cutoff "
          f"structures of these same validation clusters are in `val_fold/skipped.csv`.\n")
    print("## Every cluster\n")
    print("Sorted by post-cutoff complexes, then size. `split` is where the cluster sits today; "
          "`val-folding` marks the 21 clusters in the running post-cutoff validation fold.\n")
    print("| cluster | complexes | pre-cutoff | post-cutoff | % post | instances | split |")
    print("|---|---|---|---|---|---|---|")
    for c, n, npre, npost, frac, ni, split in rows:
        print(f"| {c} | {n} | {npre} | {npost} | {100*frac:.0f}% | {ni} | {split} |")


if __name__ == "__main__":
    main()
